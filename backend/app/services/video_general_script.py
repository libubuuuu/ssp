async def analyze_video(
    *,
    video_url: str,
    product_image_urls: list,
    market: str = "海外",
    duration: int = 15,
    model_info: str = "AI 自动生成模特",
    user_idea: str = "",
) -> str:
    """分析参考视频，拆解分镜后替换产品生成新脚本。

    Args:
        video_url: 参考视频 URL（fal storage）
        product_image_urls: 产品图 URL 列表（正面必传）
        market: 目标市场
        duration: 目标时长（秒）
        model_info: 模特信息
        user_idea: 用户额外要求

    Returns:
        结构化脚本文字字符串
    """
    prompt = _PROMPT_VIDEO_ANALYZE \
        .replace("{market}", market) \
        .replace("{duration}", str(duration)) \
        .replace("{model_info}", model_info or "AI 自动生成模特") \
        .replace("{user_idea}", user_idea or "无")

    import random
    prompt = prompt + f"\n⚡ 本次创作指令：重点围绕你分析出的第{random.randint(1,3)}个痛点展开，使用第{random.randint(1,3)}种场景方向，选择第{random.randint(1,3)}种角色身份。确保与其他版本完全不同。\n"

    log_info(
        f"video_analyze: market={market} duration={duration}s "
        f"n_product_imgs={len(product_image_urls)} video={video_url[:60]}"
    )

    script = await ask_gemini(
        prompt=prompt,
        video_url=video_url,
        image_urls=list(product_image_urls[:4]),
        max_tokens=8192,
        temperature=0.7,
        model="gemini-2.5-flash-all",
    )

    log_info(f"video_analyze: 脚本生成完成 output_len={len(script)}")
    return script.strip()


def parse_script(text: str) -> list[dict]:
    """把 Gemini 生成的脚本文字解析为分镜列表。

    期望格式（每行一个镜头）：
      [镜头一]：0-3s | 起，展示困境，中景，...，模特说：Why does...

    Returns:
        list of {id, time_range, duration_sec, shot, action, visual_prompt, speech}
    """
    import re

    scenes: list[dict] = []
    # 匹配 [镜头X]：start-ends | 描述（允许中英文标点、全半角冒号）
    pattern = re.compile(
        r'\[镜头[一二三四五六七八九十百\d]+\][：:]\s*'
        r'(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)s\s*\|?\s*'
        r'([^\n]+)',
        re.UNICODE,
    )
    shot_keywords = ['大特写', '极近景', '特写', '近景', '中近景', '中景', '全景', '远景', '俯拍', '仰拍']

    matches = list(pattern.finditer(text))

    # 容错：如果严格模式解析到 0 个分镜，尝试不带时间的宽松模式
    if not matches:
        fallback = re.compile(
            r'\[镜头[一二三四五六七八九十百\d]+\][：:]\s*([^\n]+)',
            re.UNICODE,
        )
        fb_matches = list(fallback.finditer(text))
        if fb_matches:
            # 按 duration 均分时长
            n = len(fb_matches)
            per_sec = 4.0  # 默认每镜头 4s
            t = 0.0
            for i, fm in enumerate(fb_matches):
                rest_fb = fm.group(1).strip()
                sp_fb = re.search(r'模特说[：:]\s*(.+)$', rest_fb, re.DOTALL)
                sp_text = ""
                if sp_fb:
                    sp_text = sp_fb.group(1).strip().strip('"').strip("'")
                    rest_fb = rest_fb[:sp_fb.start()].strip().rstrip('，,').strip()
                shot_fb = "中景"
                for kw in shot_keywords:
                    if kw in rest_fb:
                        shot_fb = kw; break
                parts_fb = re.split(r'[，,]', rest_fb, maxsplit=1)
                action_fb = parts_fb[0].strip() if parts_fb else ""
                vp_fb = parts_fb[1].strip() if len(parts_fb) > 1 else rest_fb
                end_t = t + per_sec
                scenes.append({
                    "id": i + 1,
                    "time_range": f"{t:.1f}-{end_t:.1f}s",
                    "duration_sec": per_sec,
                    "shot": shot_fb, "action": action_fb,
                    "visual_prompt": vp_fb, "speech": sp_text, "stage": "",
                })
                t = end_t
            return scenes

    for m in matches:
        start    = float(m.group(1))
        end      = float(m.group(2))
        rest     = m.group(3).strip()
        duration = max(0.5, end - start)

        # 提取台词（模特说：之后直到行尾）
        speech = ""
        sp = re.search(r'模特说[：:]\s*(.+)$', rest, re.DOTALL)
        if sp:
            speech = sp.group(1).strip().strip('"').strip("'").strip('“').strip('”')
            rest = rest[:sp.start()].strip().rstrip('，,').strip()

        # 提取景别
        shot = "中景"
        for kw in shot_keywords:
            if kw in rest:
                shot = kw
                break

        # 第一段（功能定位）和描述
        parts = re.split(r'[，,]', rest, maxsplit=1)
        action      = parts[0].strip() if parts else ""
        visual_prompt = parts[1].strip() if len(parts) > 1 else rest

        # 提取起/承/转/合阶段标签
        _STAGE_MAP = {
            "起": "起", "hook": "起", "钩子": "起", "冲突": "起", "困境": "起",
            "承": "承", "升级": "承", "受挫": "承", "危机": "承",
            "转": "转", "救场": "转", "反转": "转",
            "合": "合", "促单": "合", "cta": "合", "逼单": "合",
        }
        stage = ""
        _search_text = (action + " " + rest).lower()
        for kw, s in _STAGE_MAP.items():
            if kw in _search_text:
                stage = s
                break

        # 提取场景标签（如 "场景：温馨卧室"）
        scene_label = ""
        _sl = re.search(r'场景[：:]\s*([^|，,\n]+)', m.group(3))
        if _sl:
            scene_label = _sl.group(1).strip()
            # 从 rest 里移除场景标签，避免混入 visual_prompt
            rest = re.sub(r'\s*场景[：:][^|，,\n]+', '', rest).strip()

        scenes.append({
            "id":            len(scenes) + 1,
            "time_range":    f"{start:.1f}-{end:.1f}s",
            "duration_sec":  duration,
            "shot":          shot,
            "action":        action,
            "visual_prompt": visual_prompt,
            "speech":        speech,
            "stage":         stage,
            "scene_label":   scene_label,
        })

    return scenes


async def generate_script(
    *,
    image_base64: str,
    image_mime: str = "image/jpeg",
    market: str = "海外",
    duration: int = 15,
    model_info: str = "AI 自动生成模特",
    user_idea: str = "",
    mode: str = "story",
) -> str:
    """根据产品图生成短视频爆款脚本。

    Args:
        image_base64: 产品图 base64（支持带/不带 data URI 前缀）
        image_mime: 图片 MIME 类型，默认 image/jpeg
        market: 目标市场，如 "海外" / "欧美" / "东南亚" / "中国"
        duration: 视频总时长（秒），5–120
        model_info: 模特信息描述
        user_idea: 用户额外想法（可为空）
        mode: "story"（剧情模式，默认）或 "direct"（直接带货）

    Returns:
        结构化脚本文字字符串

    Raises:
        RuntimeError: API 调用失败
    """
    template = _PROMPT_STORY if mode == "story" else _PROMPT_DIRECT
    prompt = template.replace("{market}", market) \
                     .replace("{duration}", str(duration)) \
                     .replace("{model_info}", model_info or "AI 自动生成模特") \
                     .replace("{user_idea}", user_idea or "无")

    import random
    prompt = prompt + f"\n⚡ 本次创作指令：重点围绕你分析出的第{random.randint(1,3)}个痛点展开，使用第{random.randint(1,3)}种场景方向，选择第{random.randint(1,3)}种角色身份。确保与其他版本完全不同。\n"

    log_info(
        f"video_general_script: mode={mode} market={market} duration={duration}s "
        f"model_info={model_info[:30] if model_info else '-'} "
        f"user_idea_len={len(user_idea)}"
    )

    script = await ask_gemini(
        prompt=prompt,
        image_base64=image_base64,
        image_mime=image_mime,
        max_tokens=8192,
        temperature=0.95,
    )

    log_info(f"video_general_script: OK mode={mode} output_len={len(script)}")
    return script.strip()
