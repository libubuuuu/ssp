async def analyze_video(
    *,
    video_url: str,
    product_image_urls: list,
    market: str = "海外",
    duration: int = 15,
    model_info: str = "AI 自动生成模特",
    user_idea: str = "",
) -> str:
    """分析参考视频，拆解分镜后替换产品生成新脚本。

    Args:
        video_url: 参考视频 URL（fal storage）
        product_image_urls: 产品图 URL 列表（正面必传）
        market: 目标市场
        duration: 目标时长（秒）
        model_info: 模特信息
        user_idea: 用户额外要求

    Returns:
        结构化脚本文字字符串
    """
    from app.services.gemini_client import ask_gemini
    from app.services.logger import log_info

    prompt = _PROMPT_VIDEO_ANALYZE \
        .replace("{market}", market) \
        .replace("{duration}", str(duration)) \
        .replace("{model_info}", model_info or "AI 自动生成模特") \
        .replace("{user_idea}", user_idea or "无")

    log_info(
        f"video_analyze: market={market} duration={duration}s "
        f"n_product_imgs={len(product_image_urls)} video={video_url[:60]}"
    )

    script = await ask_gemini(
        prompt=prompt,
        video_url=video_url,
        image_urls=product_image_urls[:4],  # 最多传4张产品图
        max_tokens=8192,
        temperature=0.7,
    )

    log_info(f"video_analyze: 脚本生成完成 output_len={len(script)}")
    return script.strip()


def parse_script(text: str) -> list[dict]:
    """把 Gemini 生成的脚本文字解析为分镜列表。

    期望格式（每行一个镜头）：
      [镜头一]：0-3s | 起，展示困境，中景，...，模特说：Why does...

    Returns:
        list of {id, time_range, duration_sec, shot, action, visual_prompt, speech}
    """
    import re

    scenes: list[dict] = []
    # 匹配 [镜头X]：start-ends | 描述（允许中英文标点、全半角冒号）
    pattern = re.compile(
        r'\[镜头[一二三四五六七八九十百\d]+\][：:]\s*'
        r'(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)s\s*\|?\s*'
        r'([^\n]+)',
        re.UNICODE,
    )
    shot_keywords = ['大特写', '极近景', '特写', '近景', '中近景', '中景', '全景', '远景', '俯拍', '仰拍']

    for m in pattern.finditer(text):
        start    = float(m.group(1))
        end      = float(m.group(2))
        rest     = m.group(3).strip()
        duration = max(0.5, end - start)

        # 提取台词（模特说：之后直到行尾）
        speech = ""
        sp = re.search(r'模特说[：:]\s*(.+)$', rest, re.DOTALL)
        if sp:
            speech = sp.group(1).strip().strip('"').strip("'").strip('“').strip('”')
            rest = rest[:sp.start()].strip().rstrip('，,').strip()

        # 提取景别
        shot = "中景"
        for kw in shot_keywords:
            if kw in rest:
                shot = kw
                break

        # 第一段（功能定位）和描述
        parts = re.split(r'[，,]', rest, maxsplit=1)
        action      = parts[0].strip() if parts else ""
        visual_prompt = parts[1].strip() if len(parts) > 1 else rest

        scenes.append({
            "id":            len(scenes) + 1,
            "time_range":    f"{start:.1f}-{end:.1f}s",
            "duration_sec":  duration,
            "shot":          shot,
            "action":        action,
            "visual_prompt": visual_prompt,
            "speech":        speech,
        })

    return scenes


async def generate_script(
    *,
    image_base64: str,
    image_mime: str = "image/jpeg",
    market: str = "海外",
    duration: int = 15,
    model_info: str = "AI 自动生成模特",
    user_idea: str = "",
    mode: str = "story",
) -> str:
    """根据产品图生成短视频爆款脚本。

    Args:
        image_base64: 产品图 base64（支持带/不带 data URI 前缀）
        image_mime: 图片 MIME 类型，默认 image/jpeg
        market: 目标市场，如 "海外" / "欧美" / "东南亚" / "中国"
        duration: 视频总时长（秒），5–120
        model_info: 模特信息描述
        user_idea: 用户额外想法（可为空）
        mode: "story"（剧情模式，默认）或 "direct"（直接带货）

    Returns:
        结构化脚本文字字符串

    Raises:
        RuntimeError: API 调用失败
    """
    template = _PROMPT_STORY if mode == "story" else _PROMPT_DIRECT
    prompt = template.replace("{market}", market) \
                     .replace("{duration}", str(duration)) \
                     .replace("{model_info}", model_info or "AI 自动生成模特") \
                     .replace("{user_idea}", user_idea or "无")

    log_info(
        f"video_general_script: mode={mode} market={market} duration={duration}s "
        f"model_info={model_info[:30] if model_info else '-'} "
        f"user_idea_len={len(user_idea)}"
    )

    script = await ask_gemini(
        prompt=prompt,
        image_base64=image_base64,
        image_mime=image_mime,
        max_tokens=8192,
        temperature=0.95,
    )

    log_info(f"video_general_script: OK mode={mode} output_len={len(script)}")
    return script.strip()
